function escapeHtml(value) {
	return String(value ?? "")
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/"/g, "&quot;")
		.replace(/'/g, "&#39;");
}

function fmt(v) {
	return v == null || v === "" ? "—" : escapeHtml(v);
}

function firstDefined(...values) {
	return values.find(
		(v) => v != null && v !== "" && !(Array.isArray(v) && v.length === 0),
	);
}

function resolveGenerationNumber(d, reward, ctx) {
	const candidates = [
		firstDefined(d.generation, reward.generation),
		normalizeGenKeyNoPrefix(ctx?.genKey),
		inferGenFromGameKey(ctx?.gameKey),
	];

	for (const candidate of candidates) {
		if (typeof candidate === "number" && Number.isFinite(candidate))
			return candidate;
		const match = String(candidate ?? "").match(/^(\d+)/);
		if (match) return Number(match[1]);
	}

	return null;
}

function resolveOtValue(d, reward, generation) {
	const explicitOt = firstDefined(
		d.ot,
		d.originalTrainer,
		d.originalTrainerName,
		d.trainerName,
		reward.ot,
		reward.originalTrainer,
		reward.originalTrainerName,
		reward.trainerName,
	);
	if (
		explicitOt != null &&
		!(Array.isArray(explicitOt) && explicitOt.length === 0)
	)
		return explicitOt;

	// Some generated Gen 3 records encode the trainer string in reward.name when no explicit OT was extracted.
	if (generation >= 3 && reward?.type === "pokemon" && reward?.name)
		return reward.name;
	return null;
}

function scrollPagerToTop(root, controlsHost) {
	const anchor =
		controlsHost?.closest?.(".dist-section") ||
		root?.closest?.(".dist-section") ||
		controlsHost ||
		root;
	if (!anchor) {
		resetAppContentScroll();
		return;
	}

	const scrollRoot = anchor.closest?.(
		".modal-content, .modal-body, [data-modal-body], #content, #legacy-content-root",
	);
	if (
		scrollRoot &&
		scrollRoot !== document.body &&
		scrollRoot !== document.documentElement
	) {
		scrollElementToTop(scrollRoot);
	}

	const top = Math.max(
		0,
		window.scrollY + anchor.getBoundingClientRect().top,
	);
	window.scrollTo({ top, behavior: "smooth" });
}

