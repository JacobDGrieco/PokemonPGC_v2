const DEFAULT_PAGE_SIZE = 30;
const PAGE_SIZE_OPTIONS = [30, 60, 120, 240];

function escapeHtml(value) {
	return String(value ?? "")
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/"/g, "&quot;")
		.replace(/'/g, "&#39;");
}

function fmt(v) {
	return v == null || v === "" ? "—" : escapeHtml(v);
}

function firstDefined(...values) {
	return values.find((v) => v != null && v !== "" && !(Array.isArray(v) && v.length === 0));
}

function getStartRaw(d) {
	const raw = d?.startDate ?? d?.["start-date"] ?? d?.start ?? d?.dates?.start ?? d?.date?.start ?? null;
	return isLikelyEventDate(raw) ? raw : null;
}

function getEndRaw(d) {
	const raw = d?.endDate ?? d?.["end-date"] ?? d?.end ?? d?.dates?.end ?? d?.date?.end ?? null;
	return isLikelyEventDate(raw) ? raw : null;
}

function getStartDisplay(d) {
	const raw = d?.startDateDisplay ?? d?.startDisplay ?? d?.dates?.startDisplay ?? d?.date?.startDisplay ?? null;
	return isLikelyEventDate(raw) ? raw : null;
}

function getEndDisplay(d) {
	const raw = d?.endDateDisplay ?? d?.endDisplay ?? d?.dates?.endDisplay ?? d?.date?.endDisplay ?? null;
	return isLikelyEventDate(raw) ? raw : null;
}

function statusRank(status) {
	const s = String(status || "").toLowerCase();
	if (s === "active") return 0;
	if (s === "upcoming") return 1;
	if (s === "permanent" || s === "ongoing") return 2;
	if (s === "expired") return 3;
	return 4;
}

function sortedDistributionsFor(gameKey) {
	return (window.DATA?.distributions?.[gameKey] || [])
		.filter(Boolean)
		.slice()
		.sort((a, b) => {
			const ad = parseToISOParts(getStartRaw(a));
			const bd = parseToISOParts(getStartRaw(b));

			if (ad && bd) return (+bd) - (+ad);
			if (ad && !bd) return -1;
			if (!ad && bd) return 1;

			const sr = statusRank(a?.status) - statusRank(b?.status);
			if (sr) return sr;

			const ai = Number(a?.id);
			const bi = Number(b?.id);
			const aOk = Number.isFinite(ai);
			const bOk = Number.isFinite(bi);
			if (aOk && bOk) return bi - ai;
			if (aOk && !bOk) return -1;
			if (!aOk && bOk) return 1;

			return String(a?.eventTitle || "").localeCompare(String(b?.eventTitle || ""));
		});
}

export function distributionsPctFor(gameKey) {
	const list = sortedDistributionsFor(gameKey);
	const total = list.length;
	if (!total) return 0;

	const statusMap =
		(window.store?.distributionsStatus instanceof Map
			? window.store.distributionsStatus.get(gameKey)
			: null) || {};

	let done = 0;
	for (const it of list) {
		const id = String(it.id);
		if (statusMap[id]) done++;
	}
	return (done / total) * 100;
}

function isAutoGeneratedNote(text) {
	const s = String(text || "");
	return (
		s.startsWith("Imported from Project Pokémon EventsGallery path:") ||
		s.startsWith("Auto-generated from GitHub path/filename only")
	);
}

function extractProjectPokemonPathSummary(d) {
	const note = asList(d.notes).find((n) => String(n).startsWith("Imported from Project Pokémon EventsGallery path:"));
	if (!note) return "";
	const fullPath = String(note).replace("Imported from Project Pokémon EventsGallery path:", "").trim();
	if (!fullPath) return "";

	const parts = fullPath.split("/").map((p) => p.trim()).filter(Boolean);
	const useful = parts
		.slice(0, -1)
		.filter((p) => !/^(Released|Unreleased|Gen\s*\d+|ENG|JPN|KOR|FRE|GER|ITA|SPA|CHS|CHT|Wondercards?)$/i.test(p))
		.filter((p) => !/^Post event redemptions$/i.test(p));

	return useful.slice(-3).join(" • ");
}

function buildDetailsLines(d) {
	const obtain = d.obtainMethod || {};
	const lines = [];

	const main = firstDefined(d.details, d.obtainText, d.description, obtain.description);
	if (main) lines.push({ text: main, kind: "main" });

	const generatedPathSummary = extractProjectPokemonPathSummary(d);
	if (!main && generatedPathSummary) {
		lines.push({ text: generatedPathSummary, kind: "main" });
	}

	if (Array.isArray(obtain.menuPath) && obtain.menuPath.length) {
		lines.push({ text: `Menu: ${obtain.menuPath.join(" → ")}`, kind: "small" });
	}
	if (obtain.code) lines.push({ text: `Code: ${obtain.code}`, kind: "small" });
	if (obtain.retailer) lines.push({ text: `Retailer: ${obtain.retailer}`, kind: "small" });
	if (obtain.location) lines.push({ text: `Location: ${obtain.location}`, kind: "small" });

	for (const req of asList(obtain.requirements)) lines.push({ text: req, kind: "small" });
	for (const extra of asList(d.extra)) lines.push({ text: extra, kind: "small" });
	for (const note of asList(d.notes).filter((x) => !isAutoGeneratedNote(x))) lines.push({ text: note, kind: "small" });

	return lines.filter((line) => line.text != null && line.text !== "");
}

function methodLabel(method) {
	const m = String(method || "").trim();
	if (!m || m.toLowerCase() === "unknown") return "";
	return prettyToken(m);
}

function statusLabel(status) {
	const s = String(status || "").trim();
	if (!s || s.toLowerCase() === "unknown") return "";
	return prettyToken(s);
}

function categoryLabel(category) {
	const c = String(category || "").trim();
	if (!c || c.toLowerCase() === "pokemon") return "";
	return prettyToken(c);
}

function listTags(values, className) {
	const list = asList(values);
	return list.length
		? list.map((o) => `<span class="tag ${className}">${fmt(o)}</span>`).join("")
		: "—";
}

function cleanGeneratedTitle(title) {
	return String(title || "")
		.replace(/\b[0-9A-F]{8}\b/gi, "")
		.replace(/\s+/g, " ")
		.trim();
}

function inferItemNameFromTitle(title) {
	const t = cleanGeneratedTitle(title);
	const m = t.match(/\bItem\s+(.+)$/i);
	if (m) return m[1].trim();
	return "";
}

function normalizeGeneratedCategory(d) {
	const c = String(d.category || "").toLowerCase();
	const title = String(d.eventTitle || "");
	if (/\bitem\b/i.test(title) && (!c || c === "pokemon")) return "key-item";
	return d.category;
}

function resolveRecord(d, ctx) {
	const reward = d.reward || {};
	const obtain = d.obtainMethod || {};
	const inferredMon = inferPokemonFromText(
		reward.species,
		reward.name,
		d.name,
		d.pokemon,
		d.eventTitle,
		d.id,
		asList(d.notes).find((n) => String(n).includes("Project Pokémon")) || ""
	);

	const inferredItem = inferItemNameFromTitle(d.eventTitle);
	const rawCategory = normalizeGeneratedCategory(d);
	const isItemLike = String(rawCategory || "").toLowerCase().includes("item") && !inferredMon;

	const name = firstDefined(
		d.name,
		d.pokemon,
		reward.species,
		reward.name,
		isItemLike ? inferredItem : null,
		inferredMon?.species,
		reward.item,
		reward.title
	);
	const nationalDex = firstDefined(reward.nationalDex, reward.natiId, reward.natId, d.nationalDex, d.natiId, inferredMon?.nationalDex);
	const gender = firstDefined(d.gender, d.sex, reward.gender, reward.sex);
	const level = firstDefined(d.level, reward.level);
	const ability = firstDefined(d.ability, reward.ability, reward.abilities);
	const nature = firstDefined(d.nature, reward.nature, reward.natures);
	const ot = firstDefined(d.ot, d.originalTrainer, reward.ot, reward.originalTrainer);
	const tid = firstDefined(d.tid, d.idno, d.trainerId, reward.tid, reward.idno, reward.trainerId);
	const held = firstDefined(d.heldItem, d.heldItems, reward.heldItem, reward.heldItems);
	const moves = firstDefined(d.moves, reward.moves);
	const ball = firstDefined(d.ball, reward.ball);
	const ribbons = firstDefined(d.ribbons, reward.ribbons);
	const shiny = firstDefined(d.shiny, reward.shiny);

	let imgSrc = firstDefined(d.img, d.image, reward.img, reward.image);
	imgSrc = resolveMaybeFn(imgSrc, ctx);
	if (!imgSrc && nationalDex) imgSrc = getPokemonSpriteUrl(nationalDex, !!shiny, ctx);

	return {
		reward,
		obtain,
		category: rawCategory,
		name,
		nationalDex,
		gender,
		level,
		abilityList: asList(ability),
		natureList: asList(nature),
		otList: asList(ot),
		idList: normalizeIdList(tid),
		heldList: normalizeNameImgList(held, ctx),
		movesNorm: normalizeMoves(moves, ctx),
		ballNorm: normalizeBall(ball, ctx),
		ribbonsNorm: normalizeRibbons(ribbons, ctx),
		imgSrc,
	};
}

function filterByRegion(list, selected) {
	const hasFilterArray = Array.isArray(selected) && selected.length && !selected.includes("all");
	const hasFilterString = typeof selected === "string" && selected.trim().toLowerCase() !== "all";
	if (!hasFilterArray && !hasFilterString) return list;

	const wanted = hasFilterArray
		? selected.map((x) => x.toString().trim().toLowerCase()).filter(Boolean)
		: [selected.toString().trim().toLowerCase()];

	return list.filter((d) => {
		const regions = normalizeRegions(d.region || d.regions || d.regionCode || d.country);
		if (!regions.length) {
			const langs = asList(d.languages).map((x) => String(x).toLowerCase());
			return langs.some((r) => wanted.includes(r));
		}
		if (regions.includes("region free")) return true;
		return regions.some((r) => wanted.includes(r));
	});
}

function makePager({ page, totalPages, totalItems, pageSize, start, end }) {
	const el = document.createElement("div");
	el.className = "dist-pager";
	el.style.cssText = "display:flex;align-items:center;justify-content:space-between;gap:12px;flex-wrap:wrap;margin:0 0 12px;";
	el.innerHTML = `
		<div class="dist-pager-info" style="font-size:12px;opacity:.85;">
			Showing ${totalItems ? start + 1 : 0}-${end} of ${totalItems} distributions
		</div>
		<div class="dist-pager-actions" style="display:flex;align-items:center;gap:8px;flex-wrap:wrap;">
			<button type="button" class="dist-page-btn" data-page-action="first" ${page <= 1 ? "disabled" : ""}>First</button>
			<button type="button" class="dist-page-btn" data-page-action="prev" ${page <= 1 ? "disabled" : ""}>Prev</button>
			<span style="font-size:12px;opacity:.85;">Page ${page} / ${totalPages}</span>
			<button type="button" class="dist-page-btn" data-page-action="next" ${page >= totalPages ? "disabled" : ""}>Next</button>
			<button type="button" class="dist-page-btn" data-page-action="last" ${page >= totalPages ? "disabled" : ""}>Last</button>
			<label style="font-size:12px;opacity:.85;display:flex;align-items:center;gap:4px;">
				Per page
				<select class="dist-page-size">
					${PAGE_SIZE_OPTIONS.map((n) => `<option value="${n}" ${n === pageSize ? "selected" : ""}>${n}</option>`).join("")}
				</select>
			</label>
		</div>
	`;
	return el;
}

function makeCard({ d, ctx, checked, setChecked }) {
	const rec = resolveRecord(d, ctx);
	const card = document.createElement("article");
	card.className = "dist-card" + (checked ? " is-done" : "");
	card.setAttribute("role", "group");
	card.setAttribute("aria-label", rec.name || d?.eventTitle || "Distribution");

	const evtTitle = cleanGeneratedTitle(d.eventTitle || rec.name || "Distribution");
	const rawRegions = d.region || d.regions || d.regionCode || d.country || null;
	let regionTokens = splitRegionsForDisplay(rawRegions);
	if (!regionTokens.length) regionTokens = asList(d.languages).map(prettyToken).filter(Boolean);

	const dateLine =
		formatDateRange({
			start: getStartRaw(d),
			end: getEndRaw(d),
			startDisplay: getStartDisplay(d),
			endDisplay: getEndDisplay(d),
		}) || formatDateRange(d.dates || d.date);

	const metaChips = [methodLabel(d.method), statusLabel(d.status), categoryLabel(rec.category)].filter(Boolean);
	const detailLines = buildDetailsLines(d);
	const hasPayload = !!(
		rec.level || rec.abilityList.length || rec.otList.length || rec.natureList.length ||
		rec.idList.length || rec.heldList.length || rec.movesNorm.length || rec.ballNorm.name ||
		rec.ballNorm.img || rec.ribbonsNorm.length
	);

	card.innerHTML = `
		<div class="dist-event-row">
			<div class="dist-event-title" title="${fmt(evtTitle)}">${fmt(evtTitle)}</div>
			${regionTokens.length || metaChips.length
				? `<div class="dist-region-list">
					${regionTokens.map((r) => `<span class="dist-region-pill">${fmt(r)}</span>`).join("")}
					${metaChips.map((r) => `<span class="dist-region-pill dist-meta-pill">${fmt(r)}</span>`).join("")}
				</div>`
				: ""
			}
		</div>

		<div class="dist-hd">
			<div class="dist-hd-left">
				<div class="dist-name">
					${fmt(rec.name)}
					<span class="dist-gender">${renderGenderSymbols(rec.gender)}</span>
				</div>
			</div>

			<div class="dist-hd-center">
				${dateLine ? `<div class="dist-dates">${fmt(dateLine)}</div>` : ``}
			</div>

			<div class="dist-hd-right dist-badges">
				${rec.ballNorm.img
					? `<img class="badge ball" alt="${fmt(rec.ballNorm.name)}" title="${fmt(rec.ballNorm.name)}" src="${rec.ballNorm.img}">`
					: rec.ballNorm.name
						? `<span class="badge ball-label">${fmt(rec.ballNorm.name)}</span>`
						: ""
				}
				${rec.ribbonsNorm
					.map((r) => r.img
						? `<img class="badge ribbon" alt="${fmt(r.name)}" title="${fmt(r.name)}" src="${r.img}">`
						: `<span class="badge ribbon-label">${fmt(r.name)}</span>`
					)
					.join("")}
			</div>
		</div>

		${!hasPayload && !rec.imgSrc
			? `<div class="dist-data-warning" style="font-size:11px;opacity:.7;text-align:center;margin:8px 0 0;">Only filename metadata was generated for this entry.</div>`
			: ""
		}

		<div class="dist-body">
			<div class="dist-img">
				${rec.imgSrc ? `<img alt="${fmt(rec.name || evtTitle)}" src="${rec.imgSrc}" loading="lazy">` : ""}
				${renderDistBadges(d)}
			</div>

			<div class="dist-specs-wrap">
				<dl class="dist-specs">
					<div><dt>Level</dt><dd>${fmt(rec.level)}</dd></div>
					<div><dt>Ability</dt><dd>${listTags(rec.abilityList, "ot")}</dd></div>
					<div><dt>OT</dt><dd>${listTags(rec.otList, "ot")}</dd></div>
					<div><dt>Nature</dt><dd>${listTags(rec.natureList, "ot")}</dd></div>
					<div><dt>ID</dt><dd>${listTags(rec.idList, "tid")}</dd></div>
					<div>
						<dt>Held Item</dt>
						<dd class="held-items" style="flex-direction: row;">
							${rec.heldList.length
								? rec.heldList.map((h) => h.img
									? `<img class="held-item-img" alt="${fmt(h.name)}" title="${fmt(h.name)}" src="${h.img}">`
									: `<span class="tag item">${fmt(h.name)}</span>`
								).join("")
								: "—"
							}
						</dd>
					</div>
				</dl>
			</div>
		</div>

		${rec.movesNorm.length
			? `<div class="dist-moves diamond" style="margin: 20px 0px;">
				${[0, 1, 2, 3].map((i) => {
					const mv = rec.movesNorm[i];
					if (!mv) return `<div class="mv"></div>`;
					const typeClass = mv.type ? ` type-${String(mv.type).toLowerCase()}` : "";
					return `<div class="mv${typeClass}" ${mv.type ? `data-type="${fmt(mv.type)}"` : ""}>
						${mv.img
							? `<img alt="${fmt(mv.name || "Move")}" title="${fmt(mv.name)}" src="${mv.img}">`
							: `<span class="mv-label">${fmt(mv.name)}</span>`
						}
					</div>`;
				}).join("")}
			</div>`
			: ""
		}

		${detailLines.length
			? `<div class="dist-details" style="margin: 10px 0px;">
				${detailLines.map((line, index) => {
					const cls = line.kind === "main" && index === 0 ? "line" : "line small";
					const style = line.kind === "main" && index === 0 ? " style=\"margin-bottom: 20px;\"" : "";
					return `<div class="${cls}"${style}>${fmt(line.text)}</div>`;
				}).join("")}
			</div>`
			: ""
		}

		<button class="dist-toggle" aria-pressed="${checked ? "true" : "false"}">
			${checked ? "Uncheck" : "Check"}
		</button>
	`;

	card.querySelectorAll("img").forEach((img) => {
		img.addEventListener("error", () => img.remove());
	});

	const btn = card.querySelector(".dist-toggle");
	btn.addEventListener("click", () => {
		const next = !(btn.getAttribute("aria-pressed") === "true");
		btn.setAttribute("aria-pressed", String(next));
		btn.textContent = next ? "Uncheck" : "Check";
		card.classList.toggle("is-done", next);
		setChecked(d.id, next);
	});

	return card;
}

export function renderDistributionCardsFor(gameKey, genKey, store, opts = {}) {
	const root = document.createElement("div");
	root.className = "dist-results";

	const rawList = sortedDistributionsFor(gameKey);
	const filteredList = filterByRegion(rawList, opts.region);
	let pageSize = Number(window.localStorage?.getItem?.("ppgc:distPageSize")) || DEFAULT_PAGE_SIZE;
	if (!PAGE_SIZE_OPTIONS.includes(pageSize)) pageSize = DEFAULT_PAGE_SIZE;
	let page = 1;

	const bucket =
		(store.distributionsStatus instanceof Map
			? store.distributionsStatus.get(gameKey)
			: null) || {};

	const setChecked = (distId, val) => {
		const rec =
			(store.distributionsStatus instanceof Map
				? store.distributionsStatus.get(gameKey)
				: null) || {};
		rec[String(distId)] = !!val;
		if (store.distributionsStatus instanceof Map) store.distributionsStatus.set(gameKey, rec);
		save();
		window.PPGC?.refreshSectionHeaderPct?.();
	};

	const renderPage = () => {
		root.innerHTML = "";
		const totalItems = filteredList.length;
		const totalPages = Math.max(1, Math.ceil(totalItems / pageSize));
		page = Math.min(Math.max(1, page), totalPages);
		const start = (page - 1) * pageSize;
		const end = Math.min(start + pageSize, totalItems);
		const pageItems = filteredList.slice(start, end);

		if (!totalItems) {
			const empty = document.createElement("div");
			empty.className = "small";
			empty.style.opacity = ".8";
			empty.textContent = "No distributions defined for this game.";
			root.appendChild(empty);
			return;
		}

		const topPager = makePager({ page, totalPages, totalItems, pageSize, start, end });
		root.appendChild(topPager);

		const grid = document.createElement("div");
		grid.className = "dist-grid";
		for (const d of pageItems) {
			const checked = !!bucket[String(d.id)];
			grid.appendChild(makeCard({ d, ctx: { gameKey, genKey }, checked, setChecked }));
		}
		root.appendChild(grid);

		const bottomPager = makePager({ page, totalPages, totalItems, pageSize, start, end });
		bottomPager.style.margin = "12px 0 0";
		root.appendChild(bottomPager);
	};

	root.addEventListener("click", (e) => {
		const btn = e.target?.closest?.("[data-page-action]");
		if (!btn) return;
		const totalPages = Math.max(1, Math.ceil(filteredList.length / pageSize));
		const action = btn.getAttribute("data-page-action");
		if (action === "first") page = 1;
		if (action === "prev") page = Math.max(1, page - 1);
		if (action === "next") page = Math.min(totalPages, page + 1);
		if (action === "last") page = totalPages;
		renderPage();
		root.scrollIntoView?.({ block: "start", behavior: "smooth" });
	});

	root.addEventListener("change", (e) => {
		const select = e.target?.closest?.(".dist-page-size");
		if (!select) return;
		pageSize = Number(select.value) || DEFAULT_PAGE_SIZE;
		window.localStorage?.setItem?.("ppgc:distPageSize", String(pageSize));
		page = 1;
		renderPage();
	});

	renderPage();
	return root;
}

(function attachSectionMeter() {
	window.PPGC = window.PPGC || {};
	const meter = (sectionObj, gameKey) => {
		const title = (sectionObj?.title || "").trim().toLowerCase();
		const id = (sectionObj?.id || "").trim().toLowerCase();
		const tags = Array.isArray(sectionObj?.tags) ? sectionObj.tags.map((x) => String(x).toLowerCase()) : [];
		if (title !== "distributions" && id !== "distributions" && !tags.includes("distributions")) return null;
		return distributionsPctFor(gameKey);
	};
	meter.__ppgcDistributionsMeter = true;
	window.PPGC.sectionMeters = Array.isArray(window.PPGC.sectionMeters) ? window.PPGC.sectionMeters : [];
	if (!window.PPGC.sectionMeters.some((fn) => fn?.__ppgcDistributionsMeter)) {
		window.PPGC.sectionMeters.push(meter);
	}
})();
