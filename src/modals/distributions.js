function compressIdRanges(values) {
	const list = asList(values)
		.map((value) => String(value))
		.filter(Boolean);
	if (!list.length) return [];

	const fixedWidth = list.every(
		(value) => /^\d+$/.test(value) && value.length === list[0].length,
	);
	if (!fixedWidth) return [...new Set(list)];

	const width = list[0].length;
	const numbers = [
		...new Set(list.map((value) => Number(value)).filter(Number.isFinite)),
	].sort((a, b) => a - b);
	if (!numbers.length) return [];

	const out = [];
	let start = numbers[0];
	let prev = numbers[0];
	for (let i = 1; i <= numbers.length; i++) {
		const current = numbers[i];
		if (current === prev + 1) {
			prev = current;
			continue;
		}
		const startText = String(start).padStart(width, "0");
		const endText = String(prev).padStart(width, "0");
		out.push(start === prev ? startText : `${startText}-${endText}`);
		start = current;
		prev = current;
	}
	return out.filter(Boolean);
}

