function statusRank(status) {
	const s = String(status || "").toLowerCase();
	if (s === "active") return 0;
	if (s === "upcoming") return 1;
	if (s === "permanent" || s === "ongoing") return 2;
	if (s === "expired") return 3;
	return 4;
}

function sortedDistributionsFor(gameKey) {
	return (window.DATA?.distributions?.[gameKey] || [])
		.filter(Boolean)
		.slice()
		.sort((a, b) => {
			const ad = parseToISOParts(getStartRaw(a));
			const bd = parseToISOParts(getStartRaw(b));

			if (ad && bd) return +bd - +ad;
			if (ad && !bd) return -1;
			if (!ad && bd) return 1;

			const sr = statusRank(a?.status) - statusRank(b?.status);
			if (sr) return sr;

			const ai = Number(a?.id);
			const bi = Number(b?.id);
			const aOk = Number.isFinite(ai);
			const bOk = Number.isFinite(bi);
			if (aOk && bOk) return bi - ai;
			if (aOk && !bOk) return -1;
			if (!aOk && bOk) return 1;

			return String(a?.eventTitle || "").localeCompare(
				String(b?.eventTitle || ""),
			);
		});
}

export function distributionsPctFor(gameKey) {
	const list = sortedDistributionsFor(gameKey);
	const total = list.length;
	if (!total) return 0;

	const statusMap =
		(window.store?.distributionsStatus instanceof Map
			? window.store.distributionsStatus.get(gameKey)
			: null) || {};

	let done = 0;
	for (const it of list) {
		const id = String(it.id);
		if (statusMap[id]) done++;
	}
	return (done / total) * 100;
}

function isAutoGeneratedNote(text) {
	const s = String(text || "");
	return (
		s.startsWith("Imported from Project Pokémon EventsGallery path:") ||
		s.startsWith("Auto-generated from GitHub path/filename only")
	);
}

function extractProjectPokemonPathSummary(d) {
	const note = asList(d.notes).find((n) =>
		String(n).startsWith(
			"Imported from Project Pokémon EventsGallery path:",
		),
	);
	if (!note) return "";
	const fullPath = String(note)
		.replace("Imported from Project Pokémon EventsGallery path:", "")
		.trim();
	if (!fullPath) return "";

	const parts = fullPath
		.split("/")
		.map((p) => p.trim())
		.filter(Boolean);
	const useful = parts
		.slice(0, -1)
		.filter(
			(p) =>
				!/^(Released|Unreleased|Gen\s*\d+|ENG|JPN|KOR|FRE|GER|ITA|SPA|CHS|CHT|Wondercards?)$/i.test(
					p,
				),
		)
		.filter((p) => !/^Post event redemptions$/i.test(p));

	return useful.slice(-3).join(" • ");
}

function buildDetailsLines(d) {
	const obtain = d.obtainMethod || {};
	const lines = [];

	const main = firstDefined(
		d.details,
		d.obtainText,
		d.description,
		obtain.description,
	);
	if (main) lines.push({ text: main, kind: "main" });

	const generatedPathSummary = extractProjectPokemonPathSummary(d);
	if (!main && generatedPathSummary) {
		lines.push({ text: generatedPathSummary, kind: "main" });
	}

	if (Array.isArray(obtain.menuPath) && obtain.menuPath.length) {
		lines.push({
			text: `Menu: ${obtain.menuPath.join(" → ")}`,
			kind: "small",
		});
	}
	if (obtain.code)
		lines.push({ text: `Code: ${obtain.code}`, kind: "small" });
	if (obtain.retailer)
		lines.push({ text: `Retailer: ${obtain.retailer}`, kind: "small" });
	for (const req of asList(obtain.requirements))
		lines.push({ text: req, kind: "small" });
	for (const extra of asList(d.extra))
		lines.push({ text: extra, kind: "small" });
	for (const note of asList(d.notes).filter((x) => !isAutoGeneratedNote(x)))
		lines.push({ text: note, kind: "small" });

	return lines.filter((line) => line.text != null && line.text !== "");
}

